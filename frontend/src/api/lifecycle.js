import { get, patch, post, put } from './client';

export const lifecycle = {
  policy: () => get('/lifecycle/settings'),
  savePolicy: (p) => put('/lifecycle/settings', p),
  templates: (kind) => get('/lifecycle/templates', { kind }),
  createTemplate: (b) => post('/lifecycle/templates', b),
  updateTemplate: (id, b) => put(`/lifecycle/templates/${id}`, b),
  cases: (q = {}) => get('/lifecycle/cases', q),
  startOnboarding: (b) => post('/lifecycle/cases', b),
  case: (id) => get(`/lifecycle/cases/${id}`),
  cancelCase: (id) => post(`/lifecycle/cases/${id}/cancel`),
  addTask: (caseId, b) => post(`/lifecycle/cases/${caseId}/tasks`, b),
  updateTask: (id, b) => patch(`/lifecycle/tasks/${id}`, b),
  comments: (taskId) => get(`/lifecycle/tasks/${taskId}/comments`),
  addComment: (taskId, body) => post(`/lifecycle/tasks/${taskId}/comments`, { body }),
  myTasks: () => get('/lifecycle/my-tasks'),
  employeeSummary: (id) => get(`/lifecycle/employees/${id}/summary`),
  probation: (within = 60) => get('/lifecycle/probation', { within }),
  submitReview: (b) => post('/lifecycle/probation/reviews', b),
  confirm: (employeeId, confirmedOn) => post('/lifecycle/probation/confirm', { employeeId, confirmedOn }),
  exits: (status) => get('/lifecycle/exits', { status }),
  myExits: () => get('/lifecycle/exits/mine'),
  resign: (b) => post('/lifecycle/exits/resign', b),
  recordExit: (b) => post('/lifecycle/exits', b),
  exit: (id) => get(`/lifecycle/exits/${id}`),
  updateExit: (id, b) => patch(`/lifecycle/exits/${id}`, b),
  withdraw: (id) => post(`/lifecycle/exits/${id}/withdraw`),
  cancelExit: (id, reason) => post(`/lifecycle/exits/${id}/cancel`, { reason }),
  completeExit: (id, skipOpenTasks = false) => post(`/lifecycle/exits/${id}/complete`, { skipOpenTasks }),
  questions: () => get('/lifecycle/exit-questions'),
  saveQuestions: (questions) => put('/lifecycle/exit-questions', { questions }),
  interview: (exitId) => get(`/lifecycle/exits/${exitId}/interview`),
  submitInterview: (exitId, answers) => post(`/lifecycle/exits/${exitId}/interview`, { answers }),
  assetTypes: () => get('/lifecycle/asset-types'),
  createAssetType: (name) => post('/lifecycle/asset-types', { name }),
  assets: (q = {}) => get('/lifecycle/assets', q),
  myAssets: () => get('/lifecycle/assets/mine'),
  createAsset: (b) => post('/lifecycle/assets', b),
  updateAsset: (id, b) => patch(`/lifecycle/assets/${id}`, b),
  assignAsset: (id, b) => post(`/lifecycle/assets/${id}/assign`, b),
  returnAsset: (id, b) => post(`/lifecycle/assets/${id}/return`, b),
};

