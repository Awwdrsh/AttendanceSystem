export type Key = keyof typeof dict;

export function translate(_lang: Lang, key: Key): string {
  return dict[key];
}

/** Kept for older call sites; returns the English label. */
export function bilingual(key: Key): string {
  return dict[key];
}

export interface I18n { lang: Lang; numerals: Numerals; t: (k: Key) => string; both: (k: Key) => string }

export const I18nContext = createContext<I18n>({ lang: 'en', numerals: 'latin', t: (k) => dict[k], both: bilingual });

export const useI18n = (): I18n => useContext(I18nContext);
