export type Key = keyof typeof dict;

export function translate(lang: Lang, key: Key): string {
  const pair = dict[key];
  return lang === 'ne' ? pair[1] : pair[0];
}

/** "बिदा / Leave" style label for headings both audiences read (plan §13.11). */
export function bilingual(key: Key): string {
  const pair = dict[key];
  return pair[0] === pair[1] ? pair[0] : `${pair[1]} / ${pair[0]}`;
}

export interface I18n { lang: Lang; setLang: (l: Lang) => void; numerals: Numerals; setNumerals: (n: Numerals) => void; t: (k: Key) => string; both: (k: Key) => string }

export const I18nContext = createContext<I18n>({
  lang: 'en', setLang: () => undefined, numerals: 'latin', setNumerals: () => undefined, t: (k) => translate('en', k), both: bilingual,
});

export const useI18n = (): I18n => useContext(I18nContext);
